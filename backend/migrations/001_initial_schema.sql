CREATE TABLE IF NOT EXISTS hero_slides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  image_url TEXT NOT NULL,
  eyebrow VARCHAR(120) NOT NULL DEFAULT '',
  heading VARCHAR(160) NOT NULL,
  description VARCHAR(600) NOT NULL DEFAULT '',
  primary_button_text VARCHAR(60) NOT NULL DEFAULT 'Shop Now',
  primary_button_url VARCHAR(500) NOT NULL DEFAULT '/shop',
  secondary_button_text VARCHAR(60) NOT NULL DEFAULT 'Explore Categories',
  secondary_button_url VARCHAR(500) NOT NULL DEFAULT '/categories',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  position INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS hero_slides_active_position_idx
  ON hero_slides (is_active, position, id);
